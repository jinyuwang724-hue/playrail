#!/usr/bin/env node
/**
 * Cocoon Design System — Multi-Platform Token Generator
 *
 * Single Source of Truth: docs/design/cocoon/tokens.json (W3C DTCG format)
 * Outputs:
 *   1. frontend/cocoon-ui/Tokens/CocoonTokens.g.cs       (C# WinUI 3 / Win2D, NativeAOT zero-reflection)
 *   2. packages/cocoon-tokens/package.json               (Reusable npm package manifest)
 *   3. packages/cocoon-tokens/dist/tokens.css            (Web CSS Custom Properties + surface recipes)
 *   4. packages/cocoon-tokens/dist/tailwind.preset.js    (Tailwind CSS preset)
 *   5. packages/cocoon-tokens/dist/tokens.kt             (Android Jetpack Compose)
 *   6. packages/cocoon-tokens/dist/tokens.dart           (Flutter)
 *
 * Usage:
 *   node tools/Build-CocoonTokens.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const tokensPath = path.join(rootDir, 'docs', 'design', 'cocoon', 'tokens.json');

const raw = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));
const dpRatio = raw.meta.referenceCanvas.dpToDesignPx.$value; // 1.75
const version = raw.meta.version.$value;

// ---------- Helpers ----------

function parseHexColor(hex) {
  const clean = hex.replace(/^#/, '');
  if (clean.length === 6) {
    const r = parseInt(clean.slice(0, 2), 16);
    const g = parseInt(clean.slice(2, 4), 16);
    const b = parseInt(clean.slice(4, 6), 16);
    return {
      a: 255,
      r,
      g,
      b,
      hex6: `#${clean.toUpperCase()}`,
      css: `#${clean.toUpperCase()}`,
      argbHex: `FF${clean.toUpperCase()}`,
    };
  }
  if (clean.length === 8) {
    const r = parseInt(clean.slice(0, 2), 16);
    const g = parseInt(clean.slice(2, 4), 16);
    const b = parseInt(clean.slice(4, 6), 16);
    const a = parseInt(clean.slice(6, 8), 16);
    const alpha = +(a / 255).toFixed(4);
    const aHex = a.toString(16).padStart(2, '0').toUpperCase();
    return {
      a,
      r,
      g,
      b,
      hex6: `#${clean.slice(0, 6).toUpperCase()}`,
      css: `rgba(${r}, ${g}, ${b}, ${alpha})`,
      argbHex: `${aHex}${clean.slice(0, 6).toUpperCase()}`,
    };
  }
  throw new Error(`Unsupported color hex: ${hex}`);
}

function parsePx(val) {
  if (typeof val === 'number') return val;
  const m = String(val).match(/^(-?\d+(?:\.\d+)?)px$/);
  if (!m) throw new Error(`Expected px dimension, got: ${val}`);
  return parseFloat(m[1]);
}

function parseMs(val) {
  if (typeof val === 'number') return val;
  const m = String(val).match(/^(-?\d+(?:\.\d+)?)ms$/);
  if (!m) throw new Error(`Expected ms duration, got: ${val}`);
  return parseFloat(m[1]);
}

function toDp(px) {
  if (px >= 9999) return 9999;
  return +(px / dpRatio).toFixed(2);
}

function pascalCase(str) {
  return str
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

function kebabCase(str) {
  return str
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .toLowerCase();
}

function ensureWrite(relPath, content) {
  const abs = path.join(rootDir, relPath);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content, 'utf8');
  console.log(`  generated ${relPath} (${Buffer.byteLength(content, 'utf8')} bytes)`);
}

function collectLeafTokens(obj, prefix = []) {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) {
      out.push({ path: [...prefix, k], token: v });
    } else if (v && typeof v === 'object') {
      out.push(...collectLeafTokens(v, [...prefix, k]));
    }
  }
  return out;
}

const colorEntries = collectLeafTokens(raw.color);
const scaleEntries = collectLeafTokens(raw.typography.scale);
const radiusEntries = collectLeafTokens(raw.radius);
const spacingEntries = collectLeafTokens(raw.spacing);
const durationEntries = collectLeafTokens(raw.motion.duration);
const easingEntries = collectLeafTokens(raw.motion.easing);

// ---------- 1. C# WinUI 3 / Win2D (NativeAOT) ----------

function generateCSharp() {
  const lines = [
    '// <auto-generated>',
    `// Generated from docs/design/cocoon/tokens.json (v${version}) by tools/Build-CocoonTokens.mjs.`,
    '// Do not edit by hand; update tokens.json and re-run: node tools/Build-CocoonTokens.mjs',
    '// </auto-generated>',
    '#nullable enable',
    '',
    'using System;',
    'using System.Linq;',
    'using Windows.UI;',
    'using Windows.UI.Text;',
    '',
    'namespace CocoonUI.Tokens;',
    '',
    '/// <summary>Cocoon Design System strongly-typed tokens (NativeAOT-safe, zero reflection).</summary>',
    'public static class CocoonTokens',
    '{',
    `    public const string Version = "${version}";`,
    `    public const float CanvasWidth = ${parsePx(raw.meta.referenceCanvas.width.$value)}f;`,
    `    public const float CanvasHeight = ${parsePx(raw.meta.referenceCanvas.height.$value)}f;`,
    `    public const float Dp = ${dpRatio}f;`,
    '',
    '    /// <summary>CJK characters MUST stay at Medium (500) to avoid synthetic bold muddiness.</summary>',
    `    public static FontWeight TextWeight(string text, ushort latin = ${raw.typography.fontWeight.latinTitle.$value}) =>`,
    `        new(text.Any(ch => ch >= 0x2E80) ? (ushort)${raw.typography.fontWeight.cjkStandard.$value} : latin);`,
    '',
    '    public static class Colors',
    '    {',
  ];

  for (const { path: p, token } of colorEntries) {
    const name = pascalCase(p.join('_'));
    const c = parseHexColor(token.$value);
    const comment = token.$description ? ` // ${token.$description}` : '';
    const rHex = c.r.toString(16).padStart(2, '0').toUpperCase();
    const gHex = c.g.toString(16).padStart(2, '0').toUpperCase();
    const bHex = c.b.toString(16).padStart(2, '0').toUpperCase();
    lines.push(
      `        public static readonly Color ${name} = Color.FromArgb(${c.a}, 0x${rHex}, 0x${gHex}, 0x${bHex});${comment}`
    );
  }
  lines.push('    }', '');

  lines.push('    public static class FontSizes', '    {');
  for (const { path: p, token } of scaleEntries) {
    lines.push(`        public const float ${pascalCase(p.join('_'))} = ${parsePx(token.$value)}f;`);
  }
  lines.push('    }', '');

  lines.push('    public static class Radii', '    {');
  for (const { path: p, token } of radiusEntries) {
    const val = token.$type === 'number' ? token.$value : parsePx(token.$value);
    lines.push(`        public const float ${pascalCase(p.join('_'))} = ${val}f;`);
  }
  lines.push('    }', '');

  lines.push('    public static class Spacing', '    {');
  for (const { path: p, token } of spacingEntries) {
    lines.push(`        public const float ${pascalCase(p.join('_'))} = ${parsePx(token.$value)}f;`);
  }
  lines.push('    }', '');

  const f = raw.focus;
  lines.push(
    '    public static class Focus',
    '    {',
    `        public const float ThicknessScale = ${f.thicknessScale.$value}f;`,
    `        public const float StrokeWidthDp = ${f.strokeWidthDp.$value}f;`,
    `        public const float StrokeWidthPx = ${f.strokeWidthDp.$value}f * Dp;`,
    `        public const float GlowStrokeMultiplier = ${f.glowStrokeMultiplier.$value}f;`,
    `        public const float GlowBlurDp = ${f.glowBlurDp.$value}f;`,
    `        public const float RimStrokeExpandDp = ${f.rimStrokeExpandDp.$value}f;`,
    `        public const float OutsetRatio = ${f.outsetRatio.$value}f;`,
    `        public const float OutsetMinDp = ${f.outsetMinDp.$value}f;`,
    `        public const float OutsetMaxDp = ${f.outsetMaxDp.$value}f;`,
    `        public const float LegBaseDp = ${f.legBaseDp.$value}f;`,
    `        public const float GapBaseDp = ${f.gapBaseDp.$value}f;`,
    `        public const float GapMaxRatio = ${f.gapMaxRatio.$value}f;`,
    `        public const float ScaleFactorRefDp = ${f.scaleFactorRefDp.$value}f;`,
    `        public const float ScaleFactorMin = ${f.scaleFactorMin.$value}f;`,
    `        public const float ScaleFactorMax = ${f.scaleFactorMax.$value}f;`,
    `        public const float RingIconRadiusPx = ${parsePx(f.ringIcon.radiusPx.$value)}f;`,
    `        public const float RingIconArcSpanDeg = ${f.ringIcon.arcSpanDeg.$value}f;`,
    `        public const float RingIconGapDeg = ${f.ringIcon.gapDeg.$value}f;`,
    `        public const double FlowPeriodMs = ${parseMs(f.flowPeriodMs.$value)};`,
    '',
    '        /// <summary>Compute concentric outset padding and outer bracket radius for a target rectangle.</summary>',
    '        public static (float Outset, float Radius) Concentric(float targetW, float targetH, float targetRadius)',
    '        {',
    '            float outset = Math.Clamp(OutsetRatio * MathF.Min(targetW, targetH), OutsetMinDp * Dp, OutsetMaxDp * Dp) * ThicknessScale;',
    '            return (outset, targetRadius + outset / 2f);',
    '        }',
    '    }',
    '',
    '    public static class Motion',
    '    {'
  );
  for (const [k, s] of Object.entries(raw.motion.spring)) {
    if (k.startsWith('$')) continue;
    lines.push(`        public const float Spring${pascalCase(k)}Stiffness = ${s.stiffness}f;`);
    lines.push(`        public const float Spring${pascalCase(k)}DampingRatio = ${s.dampingRatio}f;`);
    if (s.delayMs) lines.push(`        public const double Spring${pascalCase(k)}DelayMs = ${s.delayMs};`);
  }
  lines.push('');
  for (const { path: p, token } of durationEntries) {
    lines.push(`        public const double Duration${pascalCase(p.join('_'))}Ms = ${parseMs(token.$value)};`);
  }
  lines.push(
    '',
    `        public const double StaggerSheetRowMs = ${parseMs(raw.motion.stagger.sheetRowMs.$value)};`,
    `        public const double StaggerLeftDrawerRowMs = ${parseMs(raw.motion.stagger.leftDrawerRowMs.$value)};`,
    `        public const float StaggerLeftDrawerOffsetX = ${parsePx(raw.motion.stagger.leftDrawerRowMs.offsetX)}f;`,
    `        public const float RubberbandMaxScale = ${raw.motion.rubberband.maxScale.$value}f;`,
    `        public const float RubberbandDistanceRatio = ${raw.motion.rubberband.distanceRatio.$value}f;`,
    `        public const float RubberbandPeakProgress = ${raw.motion.rubberband.peakProgress.$value}f;`,
    `        public const float OverscrollResistance = ${raw.motion.rubberband.overscrollResistance.$value}f;`,
    '',
    '        /// <summary>WinUI Composition SpringNaturalMotionAnimation Period (omega = 1 / Period).</summary>',
    '        public static TimeSpan CompositionSpringPeriod(float stiffness) => TimeSpan.FromSeconds(1.0 / Math.Sqrt(stiffness));',
    '    }',
    '}',
    ''
  );
  return lines.join('\n');
}

// ---------- 2. Web CSS Custom Properties + Surface Recipes ----------

function generateCss() {
  const lines = [
    '/*',
    ` * Cocoon Design System — CSS Custom Properties & Surface Recipes (v${version})`,
    ' * Auto-generated from docs/design/cocoon/tokens.json by tools/Build-CocoonTokens.mjs.',
    ' * Dimensions default to dp-scaled CSS px (design px / 1.75) for standard 1x Web/Desktop screens.',
    ' * Override --cocoon-scale to 1.75 if rendering directly on a 1920x1200 logical canvas.',
    ' */',
    '',
    ':root {',
    '  --cocoon-scale: 1;',
    `  --cocoon-dp-ratio: ${dpRatio};`,
    '',
    '  /* Colors */',
  ];

  for (const { path: p, token } of colorEntries) {
    const varName = `--cocoon-color-${p.map(kebabCase).join('-')}`;
    const c = parseHexColor(token.$value);
    lines.push(`  ${varName}: ${c.css};`);
  }

  lines.push('', '  /* Typography */');
  lines.push(
    `  --cocoon-font-latin: ${raw.typography.fontFamily.latin.$value
      .map((f) => (f.includes(' ') ? `'${f}'` : f))
      .join(', ')};`
  );
  lines.push(
    `  --cocoon-font-cjk: ${raw.typography.fontFamily.cjk.$value
      .map((f) => (f.includes(' ') ? `'${f}'` : f))
      .join(', ')};`
  );
  lines.push('  --cocoon-font-sans: var(--cocoon-font-latin), var(--cocoon-font-cjk);');
  lines.push(`  --cocoon-weight-latin-body: ${raw.typography.fontWeight.latinBody.$value};`);
  lines.push(`  --cocoon-weight-latin-title: ${raw.typography.fontWeight.latinTitle.$value};`);
  lines.push(`  --cocoon-weight-latin-badge: ${raw.typography.fontWeight.latinBadge.$value};`);
  lines.push(`  --cocoon-weight-latin-display: ${raw.typography.fontWeight.latinDisplay.$value};`);
  lines.push(`  --cocoon-weight-cjk: ${raw.typography.fontWeight.cjkStandard.$value};`);
  lines.push(`  --cocoon-weight-cjk-light: ${raw.typography.fontWeight.cjkBodyLight.$value};`);

  lines.push('', '  /* Type Scale (dp-scaled CSS px) */');
  for (const { path: p, token } of scaleEntries) {
    lines.push(`  --cocoon-text-${kebabCase(p.join('-'))}: calc(${toDp(parsePx(token.$value))}px * var(--cocoon-scale));`);
  }

  lines.push('', '  /* Radii (dp-scaled CSS px) */');
  for (const { path: p, token } of radiusEntries) {
    if (token.$type === 'number') {
      lines.push(`  --cocoon-radius-${kebabCase(p.join('-'))}: ${token.$value};`);
    } else {
      const px = parsePx(token.$value);
      lines.push(
        `  --cocoon-radius-${kebabCase(p.join('-'))}: ${
          px >= 9999 ? '9999px' : `calc(${toDp(px)}px * var(--cocoon-scale))`
        };`
      );
    }
  }

  lines.push('', '  /* Spacing (dp-scaled CSS px) */');
  for (const { path: p, token } of spacingEntries) {
    lines.push(`  --cocoon-space-${kebabCase(p.join('-'))}: calc(${toDp(parsePx(token.$value))}px * var(--cocoon-scale));`);
  }

  lines.push('', '  /* Focus & Motion */');
  lines.push(`  --cocoon-focus-stroke: calc(${raw.focus.strokeWidthDp.$value}px * var(--cocoon-scale));`);
  lines.push(`  --cocoon-focus-flow-period: ${raw.focus.flowPeriodMs.$value};`);
  for (const [k, s] of Object.entries(raw.motion.spring)) {
    if (k.startsWith('$')) continue;
    lines.push(`  --cocoon-spring-${kebabCase(k)}-stiffness: ${s.stiffness};`);
    lines.push(`  --cocoon-spring-${kebabCase(k)}-damping: ${+(2 * Math.sqrt(s.stiffness)).toFixed(2)};`);
  }
  for (const { path: p, token } of easingEntries) {
    lines.push(`  --cocoon-ease-${kebabCase(p.join('-'))}: cubic-bezier(${token.$value.join(', ')});`);
  }
  for (const { path: p, token } of durationEntries) {
    lines.push(`  --cocoon-duration-${kebabCase(p.join('-'))}: ${token.$value};`);
  }

  lines.push('', '  /* Composite Surface Gradients & Shadows */');
  lines.push(
    '  --cocoon-grad-page: linear-gradient(180deg, var(--cocoon-color-surface-page-top) 0%, var(--cocoon-color-surface-page-bottom) 100%);'
  );
  lines.push(
    '  --cocoon-grad-accent: linear-gradient(135deg, var(--cocoon-color-brand-accent-start) 0%, var(--cocoon-color-brand-accent-end) 100%);'
  );
  lines.push(
    '  --cocoon-grad-accent-x: linear-gradient(90deg, var(--cocoon-color-brand-accent-start) 0%, var(--cocoon-color-brand-accent-deep) 100%);'
  );
  lines.push(
    '  --cocoon-grad-tile-on: linear-gradient(180deg, var(--cocoon-color-brand-accent-soft-start) 0%, var(--cocoon-color-brand-accent-deep) 100%);'
  );
  lines.push(
    '  --cocoon-grad-pill-action: linear-gradient(135deg, var(--cocoon-color-brand-pill-action-start) 0%, var(--cocoon-color-brand-pill-action-end) 100%);'
  );
  lines.push(
    '  --cocoon-grad-confirm: linear-gradient(180deg, var(--cocoon-color-semantic-confirm-start) 0%, var(--cocoon-color-semantic-confirm-end) 100%);'
  );
  lines.push(
    '  --cocoon-grad-card-3d: linear-gradient(180deg, var(--cocoon-color-surface-card3d-top) 0%, var(--cocoon-color-surface-card3d-bottom) 100%);'
  );
  lines.push(
    '  --cocoon-grad-drawer: linear-gradient(180deg, var(--cocoon-color-surface-drawer-top) 0%, var(--cocoon-color-surface-drawer-top) 3%, var(--cocoon-color-surface-drawer-mid) 34%, var(--cocoon-color-surface-drawer-mid) 61%, var(--cocoon-color-surface-drawer-low) 86%, var(--cocoon-color-surface-drawer-low) 99%, var(--cocoon-color-surface-drawer-bottom-edge) 100%);'
  );
  lines.push(
    '  --cocoon-shadow-card-3d: 0 7px 14px -2px rgba(0, 0, 0, 0.20), 0 1px 3px rgba(0, 0, 0, 0.10), inset 0 1.5px 0 #FFFFFF, inset 0 -12px 14px -10px rgba(20, 20, 40, 0.08);'
  );
  lines.push('  --cocoon-shadow-group-sheet: 0 3px 6px rgba(0, 0, 0, 0.16);');
  lines.push('  --cocoon-shadow-option-card: 0 3px 8px rgba(0, 0, 0, 0.18);');
  lines.push('  --cocoon-shadow-dialog: 0 7px 22px rgba(0, 0, 0, 0.35);');
  lines.push('  --cocoon-shadow-pill: 0 2px 6px rgba(0, 0, 0, 0.14);');
  lines.push('  --cocoon-shadow-toggle-knob: 0 2px 4px rgba(0, 0, 0, 0.22);');
  lines.push('  --cocoon-shadow-slider-thumb: 0 2px 5px rgba(0, 0, 0, 0.30);');
  lines.push('  --cocoon-shadow-primary-glow: 0 5px 12px rgba(122, 60, 255, 0.45);');
  lines.push('}', '');

  lines.push(
    '/* Reusable Cocoon Surface Primitives */',
    '.cocoon-page-canvas {',
    '  background: var(--cocoon-grad-page);',
    '  color: var(--cocoon-color-neutral-ink-primary);',
    '  font-family: var(--cocoon-font-sans);',
    '  font-weight: var(--cocoon-weight-cjk);',
    '}',
    '',
    '.cocoon-card-3d {',
    '  position: relative;',
    '  border-radius: var(--cocoon-radius-card);',
    '  background: var(--cocoon-grad-card-3d) padding-box,',
    '              linear-gradient(180deg, var(--cocoon-color-surface-card3d-edge-top) 0%, var(--cocoon-color-surface-card3d-edge-bottom) 100%) border-box;',
    '  border: 1.5px solid transparent;',
    '  box-shadow: var(--cocoon-shadow-card-3d);',
    '}',
    '',
    '.cocoon-divider-groove {',
    '  height: 1.5px;',
    '  background: var(--cocoon-color-surface-divider-groove);',
    '  box-shadow: 0 1px 0 var(--cocoon-color-neutral-pure-white);',
    '}',
    '',
    '.cocoon-drawer-surface {',
    '  background: var(--cocoon-grad-drawer);',
    '}',
    '',
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    '    --cocoon-duration-toggle-slide: 1ms;',
    '    --cocoon-duration-nav-crossfade: 1ms;',
    '    --cocoon-duration-relayout-slide: 1ms;',
    '    --cocoon-duration-drawer-slide: 1ms;',
    '  }',
    '}',
    ''
  );
  return lines.join('\n');
}

// ---------- 3. Tailwind CSS Preset ----------

function generateTailwindPreset() {
  const colors = {};
  for (const { path: p } of colorEntries) {
    const key = p.map(kebabCase).join('-');
    colors[key] = `var(--cocoon-color-${key})`;
  }
  const borderRadius = {};
  for (const { path: p, token } of radiusEntries) {
    if (token.$type === 'number') continue;
    const key = kebabCase(p.join('-'));
    borderRadius[`cocoon-${key}`] = `var(--cocoon-radius-${key})`;
  }
  const fontSize = {};
  for (const { path: p } of scaleEntries) {
    const key = kebabCase(p.join('-'));
    fontSize[`cocoon-${key}`] = `var(--cocoon-text-${key})`;
  }

  return [
    '/**',
    ` * Cocoon Design System — Tailwind CSS Preset (v${version})`,
    ' * Auto-generated from docs/design/cocoon/tokens.json by tools/Build-CocoonTokens.mjs.',
    ' * Import tokens.css in your app entry and add this preset to tailwind.config.js.',
    ' */',
    '',
    'export default {',
    '  theme: {',
    '    extend: {',
    `      colors: { cocoon: ${JSON.stringify(colors, null, 8).replace(/\n/g, '\n      ')} },`,
    `      borderRadius: ${JSON.stringify(borderRadius, null, 6).replace(/\n/g, '\n      ')},`,
    `      fontSize: ${JSON.stringify(fontSize, null, 6).replace(/\n/g, '\n      ')},`,
    '      fontFamily: {',
    "        'cocoon-latin': ['Poppins', 'Segoe UI Variable Display', 'Inter', 'system-ui', 'sans-serif'],",
    "        'cocoon-cjk': ['PingFang SC', 'Microsoft YaHei UI', 'Noto Sans CJK SC', 'sans-serif'],",
    '      },',
    '      boxShadow: {',
    "        'cocoon-card-3d': 'var(--cocoon-shadow-card-3d)',",
    "        'cocoon-group-sheet': 'var(--cocoon-shadow-group-sheet)',",
    "        'cocoon-option': 'var(--cocoon-shadow-option-card)',",
    "        'cocoon-dialog': 'var(--cocoon-shadow-dialog)',",
    "        'cocoon-pill': 'var(--cocoon-shadow-pill)',",
    "        'cocoon-primary-glow': 'var(--cocoon-shadow-primary-glow)',",
    '      },',
    '    },',
    '  },',
    '};',
    '',
  ].join('\n');
}

// ---------- 4. Android Jetpack Compose (Kotlin) ----------

function generateKotlin() {
  const lines = [
    '// Auto-generated from docs/design/cocoon/tokens.json by tools/Build-CocoonTokens.mjs.',
    `// Version: ${version} | Values converted to Android dp / sp (design px / ${dpRatio}).`,
    'package design.cocoon.tokens',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    'object CocoonTokens {',
    '    object Colors {',
  ];
  for (const { path: p, token } of colorEntries) {
    const c = parseHexColor(token.$value);
    lines.push(`        val ${pascalCase(p.join('_'))} = Color(0x${c.argbHex})`);
  }
  lines.push('    }', '', '    object Radii {');
  for (const { path: p, token } of radiusEntries) {
    if (token.$type === 'number') {
      lines.push(`        const val ${pascalCase(p.join('_'))} = ${token.$value}f`);
    } else {
      lines.push(`        val ${pascalCase(p.join('_'))} = ${toDp(parsePx(token.$value))}.dp`);
    }
  }
  lines.push('    }', '', '    object TypeScale {');
  for (const { path: p, token } of scaleEntries) {
    lines.push(`        val ${pascalCase(p.join('_'))} = ${toDp(parsePx(token.$value))}.sp`);
  }
  lines.push('    }', '', '    object Spacing {');
  for (const { path: p, token } of spacingEntries) {
    lines.push(`        val ${pascalCase(p.join('_'))} = ${toDp(parsePx(token.$value))}.dp`);
  }
  lines.push('    }', '', '    object Motion {');
  for (const [k, s] of Object.entries(raw.motion.spring)) {
    if (k.startsWith('$')) continue;
    lines.push(`        const val Spring${pascalCase(k)}Stiffness = ${s.stiffness}f`);
  }
  lines.push(`        const val FocusFlowPeriodMs = ${parseMs(raw.focus.flowPeriodMs.$value)}L`);
  lines.push('    }', '}', '');
  return lines.join('\n');
}

// ---------- 5. Flutter (Dart) ----------

function generateDart() {
  const lines = [
    '// Auto-generated from docs/design/cocoon/tokens.json by tools/Build-CocoonTokens.mjs.',
    `// Version: ${version} | Logical px converted to Flutter dp (design px / ${dpRatio}).`,
    "import 'dart:ui' show Color;",
    '',
    'abstract final class CocoonTokens {',
    `  static const String version = '${version}';`,
    `  static const double dpRatio = ${dpRatio};`,
    '',
    '  // Colors',
  ];
  for (const { path: p, token } of colorEntries) {
    const c = parseHexColor(token.$value);
    lines.push(`  static const Color color${pascalCase(p.join('_'))} = Color(0x${c.argbHex});`);
  }
  lines.push('', '  // Radii (dp)');
  for (const { path: p, token } of radiusEntries) {
    const val = token.$type === 'number' ? token.$value : toDp(parsePx(token.$value));
    lines.push(`  static const double radius${pascalCase(p.join('_'))} = ${val};`);
  }
  lines.push('', '  // Spacing (dp)');
  for (const { path: p, token } of spacingEntries) {
    lines.push(`  static const double space${pascalCase(p.join('_'))} = ${toDp(parsePx(token.$value))};`);
  }
  lines.push('', '  // Springs (mass = 1, dampingRatio = 1.0)');
  for (const [k, s] of Object.entries(raw.motion.spring)) {
    if (k.startsWith('$')) continue;
    lines.push(`  static const double spring${pascalCase(k)}Stiffness = ${s.stiffness};`);
  }
  lines.push(`  static const int focusFlowPeriodMs = ${parseMs(raw.focus.flowPeriodMs.$value)};`, '}', '');
  return lines.join('\n');
}

